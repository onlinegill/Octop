#!/usr/bin/env bash
# Remove large files that the native FPK does not need:
#   - Playwright's bundled driver (Chromium is not preinstalled; install on demand from the console)
#   - googleapiclient offline discovery cache (fetched later when online)
#   - __pycache__ / *.pyc
# Usage: bash scripts/fnos/slim-site-packages.sh /path/to/site-packages
set -euo pipefail

SP="${1:-}"
[ -n "$SP" ] && [ -d "$SP" ] || {
  echo "Usage: $0 <site-packages directory>" >&2
  exit 1
}

rm -rf "${SP}/playwright/driver"
rm -rf "${SP}/googleapiclient/discovery_cache"

find "$SP" -depth -type d -name '__pycache__' -exec rm -rf {} +
find "$SP" -type f \( -name '*.pyc' -o -name '*.pyo' \) -delete

echo "[slim-site-packages] slimmed: $SP"
